"""Segment table for objl.asm: which lines each per-line sprite shows on.

Each sprite is moved every line (Y = LY+17, minus 4 for row 4) and shown at its column X on the
lines of its segments, hidden (X = 0) elsewhere. Writes objl_tables.inc for the ROM; check.py
imports SPRITES and BARS to build the expected screen.
"""
import os

# GB screen lines covered by solid BG bars (tile 1, colour 3)
BARS = [(0, 16, "top bar"), (112, 120, "keys")]

# per sprite: screen x, tile row shown (0 or 4), segments (first line, last line, label)
SPRITES = [
    (16, 0, [(16, 22, "7 lines right below the top bar"),
             (30, 69, "40 lines"),
             (71, 80, "10 lines after a 1-line gap"),
             (104, 111, "8 lines right above the keys")]),
    (48, 0, [(0, 5, "6 lines at the top edge, over the top bar"),
             (40, 50, "11 lines in free space"),
             (60, 60, "1 line"),
             (62, 63, "2 lines after a 1-line gap"),
             (120, 125, "6 lines right below the keys")]),
    (80, 4, [(16, 19, "row 4: 4 lines right below the top bar"),
             (24, 59, "row 4: 36 lines"),
             (106, 111, "row 4: 6 lines right above the keys"),
             (138, 143, "row 4: 6 lines at the bottom edge")]),
]


def xtable(x, segs):
    t = [0] * 256
    for a, b, _ in segs:
        for line in range(a, b + 1):
            t[line] = x + 8
    return t


if __name__ == "__main__":
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "objl_tables.inc")
    with open(out, "w") as f:
        f.write("; generated by gen.py: OAM X of sprites 0-2 for each line (0 = hidden), one page each\n")
        f.write("SECTION \"xt\", ROM0, ALIGN[8]\n")
        for i, (x, row, segs) in enumerate(SPRITES):
            t = xtable(x, segs)
            f.write("XT%d::\n" % i)
            for k in range(0, 256, 16):
                f.write("\tdb " + ",".join("$%02X" % v for v in t[k:k + 16]) + "\n")
